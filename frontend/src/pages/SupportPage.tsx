import React, { useState } from 'react';
import { PageHeader } from '../components/common/PageHeader';
import { Panel } from '../components/common/Panel';
import { StatusBadge } from '../components/common/StatusBadge';
import { useTheme } from '../state/ThemeContext';
import { Copy, Check, ExternalLink } from 'lucide-react';

export const SupportPage: React.FC = () => {
  const { theme, setTheme } = useTheme();
  const [copiedCmd, setCopiedCmd] = useState<string | null>(null);

  const handleCopy = (key: string, text: string) => {
    if (typeof navigator !== 'undefined' && navigator.clipboard) {
      navigator.clipboard.writeText(text);
      setCopiedCmd(key);
      setTimeout(() => setCopiedCmd(null), 2000);
    }
  };

  const apiBase =
    (typeof window !== 'undefined' && (import.meta.env.VITE_API_BASE_URL as string)) ||
    'http://localhost:8000';

  const vocabKeys = [
    { key: 'running', desc: 'Active execution step in progress' },
    { key: 'completed', desc: 'Process or step finished successfully' },
    { key: 'allowed', desc: 'Action conforms with deterministic governance policies' },
    { key: 'blocked', desc: 'Action violates hard governance limit or margin policy' },
    { key: 'awaiting_approval', desc: 'Exception requires human operator sign-off' },
    { key: 'approved', desc: 'Human operator authorized the exception' },
    { key: 'rejected', desc: 'Human operator rejected the exception with recorded reason' },
    { key: 'failed', desc: 'Workflow or communication step halted due to error' },
    { key: 'simulated', desc: 'Generated by client-side demo simulator' },
    { key: 'unavailable', desc: 'Service or data source currently unreachable' },
    { key: 'pending', desc: 'Queued awaiting precondition or predecessor step' },
  ];

  return (
    <div className="space-y-6">
      <PageHeader
        title="Support & Operational Documentation"
        description="Runbooks, governance vocabulary, API endpoints, and system limitations."
      />

      {/* Theme Preference */}
      <Panel title="Interface Theme Preference">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 text-[13px]">
          <div>
            <div className="font-medium text-text">Color Scheme</div>
            <div className="text-text-3 text-[12px]">
              Select between Mill Floor Daylight (light), Night Shift (dark), or system OS preference.
            </div>
          </div>
          <div className="inline-flex rounded-[4px] border border-border p-0.5 bg-surface-2 shrink-0">
            {(['light', 'dark', 'system'] as const).map((m) => (
              <button
                key={m}
                type="button"
                onClick={() => setTheme(m)}
                className={`px-3 py-1 text-[12px] font-medium rounded-[3px] transition-colors cursor-pointer capitalize ${
                  theme === m
                    ? 'bg-surface text-text shadow-sm'
                    : 'text-text-3 hover:text-text'
                }`}
              >
                {m}
              </button>
            ))}
          </div>
        </div>
      </Panel>

      {/* Getting Started */}
      <Panel title="Getting Started — Local Runbook">
        <div className="space-y-4 text-[13px]">
          <div>
            <div className="font-medium text-text mb-1">1. Backend Service (FastAPI)</div>
            <div className="flex items-center justify-between bg-surface-sunk border border-border rounded-[4px] p-2 font-mono text-[12px]">
              <span className="text-text truncate mr-2">
                python -m uvicorn app.main:app --host 127.0.0.1 --port 8000 --reload
              </span>
              <button
                type="button"
                onClick={() =>
                  handleCopy(
                    'backend',
                    'python -m uvicorn app.main:app --host 127.0.0.1 --port 8000 --reload'
                  )
                }
                className="p-1 text-text-3 hover:text-text cursor-pointer shrink-0"
                title="Copy command"
              >
                {copiedCmd === 'backend' ? (
                  <Check className="w-4 h-4 text-ok" />
                ) : (
                  <Copy className="w-4 h-4" />
                )}
              </button>
            </div>
          </div>

          <div>
            <div className="font-medium text-text mb-1">2. Frontend Service (Vite + React)</div>
            <div className="flex items-center justify-between bg-surface-sunk border border-border rounded-[4px] p-2 font-mono text-[12px]">
              <span className="text-text truncate mr-2">npm run dev</span>
              <button
                type="button"
                onClick={() => handleCopy('frontend', 'npm run dev')}
                className="p-1 text-text-3 hover:text-text cursor-pointer shrink-0"
                title="Copy command"
              >
                {copiedCmd === 'frontend' ? (
                  <Check className="w-4 h-4 text-ok" />
                ) : (
                  <Copy className="w-4 h-4" />
                )}
              </button>
            </div>
          </div>

          <div className="pt-2 flex items-center gap-4 text-[12px]">
            <a
              href={`${apiBase}/api/health`}
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex items-center gap-1 text-accent hover:underline font-mono"
            >
              <span>GET /api/health</span>
              <ExternalLink className="w-3 h-3" />
            </a>
            <a
              href={`${apiBase}/docs`}
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex items-center gap-1 text-accent hover:underline font-mono"
            >
              <span>OpenAPI Interactive Docs (/docs)</span>
              <ExternalLink className="w-3 h-3" />
            </a>
          </div>
        </div>
      </Panel>

      {/* Scenarios Explained */}
      <Panel title="Governed Scenarios Explained">
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-[13px]">
          <div className="p-3 rounded-[4px] border border-border bg-surface-2/40">
            <div className="font-semibold text-text mb-0.5">1. Normal Fulfillment</div>
            <p className="text-text-2 text-[12px] leading-normal">
              Inventory check confirms available steel slab stock. Finance validates budget margin. Logistics routes via standard carrier. No policy violations triggered; automatically approved and fulfilled.
            </p>
          </div>

          <div className="p-3 rounded-[4px] border border-border bg-surface-2/40">
            <div className="font-semibold text-text mb-0.5">2. Supplier Unavailable</div>
            <p className="text-text-2 text-[12px] leading-normal">
              Primary mill supplier reports inventory depletion. Procurement agent evaluates alternative bids, calculates landed cost, and recommends a replacement vendor within acceptable delivery limits.
            </p>
          </div>

          <div className="p-3 rounded-[4px] border border-border bg-surface-2/40">
            <div className="font-semibold text-text mb-0.5">3. Budget Overrun</div>
            <p className="text-text-2 text-[12px] leading-normal">
              Purchase requisition exceeds the quarterly category budget limit. Deterministic policy check triggers a hard block and routes the order to the Human-in-the-Loop Exceptions queue for executive sign-off.
            </p>
          </div>

          <div className="p-3 rounded-[4px] border border-border bg-surface-2/40">
            <div className="font-semibold text-text mb-0.5">4. Delivery Delay</div>
            <p className="text-text-2 text-[12px] leading-normal">
              Freight corridor congestion flags a 48-hour delivery delay exceeding customer SLA. Logistics agent calculates expedited multi-modal rerouting and submits feasibility evidence.
            </p>
          </div>
        </div>
      </Panel>

      {/* Status Vocabulary Reference */}
      <Panel title="Governance Status Vocabulary Reference">
        <div className="overflow-x-auto">
          <table className="w-full text-left border-collapse text-[13px]">
            <thead>
              <tr className="border-b border-border text-[11px] font-semibold text-text-3 uppercase tracking-wider">
                <th className="py-2 pr-4">Badge</th>
                <th className="py-2 pr-4">Status Key</th>
                <th className="py-2">Operational Meaning</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-border">
              {vocabKeys.map(({ key, desc }) => (
                <tr key={key} className="h-[36px]">
                  <td className="py-1.5 pr-4">
                    <StatusBadge status={key} size="sm" />
                  </td>
                  <td className="py-1.5 pr-4 font-mono text-[12px] text-text-2">
                    {key}
                  </td>
                  <td className="py-1.5 text-text-2 text-[12px]">{desc}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Panel>

      {/* Known Limitations */}
      <Panel title="Known System Limitations">
        <ul className="list-disc list-inside space-y-1.5 text-[12px] text-text-2">
          <li>
            <strong className="text-text font-medium">ERP Adapters:</strong> Action dispatch currently connects to PostgreSQL database tables acting as ERP adapter mocks for procurement and logistics.
          </li>
          <li>
            <strong className="text-text font-medium">Knowledge Graph Backend:</strong> Graph visualizer falls back to relational entity projections when the Neo4j Bolt driver is unconfigured.
          </li>
          <li>
            <strong className="text-text font-medium">Blockchain Anchoring:</strong> In default demo mode, cryptographic hashes are computed client-side without gas expenditure unless Live mode with Sepolia RPC credentials is active.
          </li>
        </ul>
      </Panel>
    </div>
  );
};
